-- Tabela: Users
CREATE TABLE IF NOT EXISTS account.users (
    email character varying(320) NOT NULL,
    email_confirmed boolean DEFAULT false,
    full_name character varying(120) NOT NULL,
    display_name character varying(60),
    gender_id integer,
    birth_date date,
    avatar text,
    cpf character varying(11),
    telefone character varying(11),
    password character varying(60) NOT NULL,
    change_password boolean DEFAULT false NOT NULL,
    accept_terms boolean DEFAULT true NOT NULL,
    root boolean DEFAULT false,
    user_fts tsvector,
    created_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    updated_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (email),
    CONSTRAINT users_gender_id_fkey FOREIGN KEY (gender_id) REFERENCES account.genders(gender_id)
);

COMMENT ON TABLE account.users IS 'Usuários do sistema. PK é o e-mail, que serve também como identificador de login.';
COMMENT ON COLUMN account.users.email            IS 'E-mail do usuário. PK natural e credencial de login.';
COMMENT ON COLUMN account.users.email_confirmed  IS 'Indica se o e-mail foi confirmado via link enviado ao usuário.';
COMMENT ON COLUMN account.users.full_name        IS 'Nome completo do usuário conforme cadastro.';
COMMENT ON COLUMN account.users.display_name     IS 'Nome exibido na interface, pode ser diferente do nome completo.';
COMMENT ON COLUMN account.users.gender_id        IS 'FK para account.genders. Opcional.';
COMMENT ON COLUMN account.users.birth_date       IS 'Data de nascimento do usuário.';
COMMENT ON COLUMN account.users.avatar           IS 'URL ou caminho da imagem de perfil do usuário.';
COMMENT ON COLUMN account.users.cpf              IS 'CPF do usuário, somente dígitos, sem formatação.';
COMMENT ON COLUMN account.users.telefone         IS 'Telefone de contato do usuário, somente dígitos.';
COMMENT ON COLUMN account.users.password         IS 'Hash bcrypt da senha do usuário.';
COMMENT ON COLUMN account.users.change_password  IS 'Quando true, força troca de senha no próximo login.';
COMMENT ON COLUMN account.users.accept_terms     IS 'Indica se o usuário aceitou os termos de uso.';
COMMENT ON COLUMN account.users.root             IS 'Quando true, o usuário tem acesso irrestrito ao sistema (superadmin).';
COMMENT ON COLUMN account.users.user_fts         IS 'Vetor FTS calculado sobre full_name e cpf (peso A), display_name (peso B) e email (peso C).';
COMMENT ON COLUMN account.users.created_at       IS 'Timestamp de criação do registro.';
COMMENT ON COLUMN account.users.updated_at       IS 'Timestamp da última atualização do registro.';

-- Tabela: Users Sessions (Audit & Auth)
CREATE TABLE IF NOT EXISTS account.users_sessions (
    session_id uuid DEFAULT gen_random_uuid() NOT NULL,
    email character varying(320) NOT NULL,
    refresh_token text NOT NULL,
    ip_address inet,
    country character varying(90),
    region character varying(120),
    city character varying(120),
    latitude double precision,
    longitude double precision,
