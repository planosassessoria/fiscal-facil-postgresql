COMMENT ON TABLE account.users_sessions IS 'Sessões ativas de usuários. Armazena refresh tokens e contexto geográfico de cada login.';
COMMENT ON COLUMN account.users_sessions.session_id     IS 'Identificador único da sessão (UUID).';
COMMENT ON COLUMN account.users_sessions.email          IS 'E-mail do usuário proprietário da sessão (FK para account.users).';
COMMENT ON COLUMN account.users_sessions.refresh_token  IS 'Token de renovação de autenticação. Deve ser armazenado com hash em produção.';
COMMENT ON COLUMN account.users_sessions.ip_address     IS 'Endereço IP de origem do login.';
COMMENT ON COLUMN account.users_sessions.country        IS 'País detectado pelo IP no momento do login.';
COMMENT ON COLUMN account.users_sessions.region         IS 'Estado/região detectado pelo IP no momento do login.';
COMMENT ON COLUMN account.users_sessions.city           IS 'Cidade detectada pelo IP no momento do login.';
COMMENT ON COLUMN account.users_sessions.latitude       IS 'Latitude geográfica aproximada do IP de origem.';
COMMENT ON COLUMN account.users_sessions.longitude      IS 'Longitude geográfica aproximada do IP de origem.';
COMMENT ON COLUMN account.users_sessions.created_at     IS 'Timestamp de criação da sessão (momento do login).';
COMMENT ON COLUMN account.users_sessions.updated_at     IS 'Timestamp da última renovação do token.';

-- Tabela: Users Tenants (Multi-tenancy Pivot) - ATUALIZADA
CREATE TABLE IF NOT EXISTS account.users_tenants (
    user_tenant_id uuid DEFAULT gen_random_uuid() NOT NULL,
    email character varying(320) NOT NULL,
    tenant_id uuid NOT NULL,
    role_id uuid,
    is_active boolean DEFAULT true,
    joined_at timestamp with time zone DEFAULT clock_timestamp(),
    CONSTRAINT users_tenants_pkey PRIMARY KEY (user_tenant_id),
    CONSTRAINT users_tenants_email_tenant_id_key UNIQUE (email, tenant_id),
    CONSTRAINT users_tenants_email_fkey FOREIGN KEY (email) REFERENCES account.users(email) ON DELETE CASCADE,
    CONSTRAINT users_tenants_role_id_fkey FOREIGN KEY (role_id) REFERENCES account.roles(role_id),
    CONSTRAINT users_tenants_tenant_id_fkey FOREIGN KEY (tenant_id) REFERENCES partner.tenants(tenant_id) ON DELETE CASCADE
);

COMMENT ON TABLE account.users_tenants IS
    'Tabela pivot de multi-tenancy. Vincula usuários a tenants com uma role específica. '
    'Um mesmo usuário pode pertencer a múltiplos tenants com roles diferentes.';
COMMENT ON COLUMN account.users_tenants.user_tenant_id IS 'Identificador único do vínculo usuário-tenant (UUID).';
COMMENT ON COLUMN account.users_tenants.email          IS 'E-mail do usuário vinculado (FK para account.users).';
COMMENT ON COLUMN account.users_tenants.tenant_id      IS 'Tenant ao qual o usuário pertence (FK para partner.tenants).';
COMMENT ON COLUMN account.users_tenants.role_id        IS 'Role atribuída ao usuário neste tenant (FK para account.roles).';
COMMENT ON COLUMN account.users_tenants.is_active      IS 'Indica se o vínculo está ativo. Falso suspende o acesso sem remover o registro.';
COMMENT ON COLUMN account.users_tenants.joined_at      IS 'Timestamp de quando o usuário foi adicionado ao tenant.';

