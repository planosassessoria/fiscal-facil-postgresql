-- Tabela: Genders
CREATE TABLE IF NOT EXISTS account.genders (
    gender_id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    gender_name character varying(30) NOT NULL,
    CONSTRAINT genders_pkey PRIMARY KEY (gender_id)
);
COMMENT ON TABLE account.genders IS 'Tabela de domínio para gêneros do usuário.';
COMMENT ON COLUMN account.genders.gender_id   IS 'Identificador numérico do gênero, gerado por identidade.';
COMMENT ON COLUMN account.genders.gender_name IS 'Rótulo do gênero exibido na interface (ex: Feminino, Masculino).';

-- Tabela: Modules (RBAC)
CREATE TABLE IF NOT EXISTS account.modules (
    module_id uuid DEFAULT gen_random_uuid() NOT NULL,
    module_name character varying(100) NOT NULL,
    module_key character varying(50) NOT NULL,
    description text,
    is_active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    updated_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    CONSTRAINT modules_pkey PRIMARY KEY (module_id),
    CONSTRAINT modules_key_unique UNIQUE (module_key)
);

COMMENT ON TABLE account.modules IS 'Módulos funcionais do sistema utilizados no controle de acesso por papel (RBAC).';
COMMENT ON COLUMN account.modules.module_id   IS 'Identificador único do módulo (UUID).';
COMMENT ON COLUMN account.modules.module_name IS 'Nome legível do módulo exibido na interface de administração.';
COMMENT ON COLUMN account.modules.module_key  IS 'Chave técnica única do módulo, usada no código (ex: "fiscal", "users", "establishments").';
COMMENT ON COLUMN account.modules.description IS 'Descrição opcional do propósito do módulo.';
COMMENT ON COLUMN account.modules.is_active   IS 'Indica se o módulo está ativo e disponível para atribuição a roles.';
COMMENT ON COLUMN account.modules.created_at  IS 'Timestamp de criação do registro.';
COMMENT ON COLUMN account.modules.updated_at  IS 'Timestamp da última atualização do registro.';

-- Tabela: Permissions (RBAC)
CREATE TABLE IF NOT EXISTS account.permissions (
    permission_id uuid DEFAULT gen_random_uuid() NOT NULL,
    module_id uuid NOT NULL,
    permission_name character varying(100) NOT NULL,
    permission_key character varying(100) NOT NULL,
    description text,
    created_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    updated_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    CONSTRAINT permissions_pkey PRIMARY KEY (permission_id),
    CONSTRAINT permissions_key_unique UNIQUE (permission_key),
    CONSTRAINT fk_permissions_module FOREIGN KEY (module_id)
        REFERENCES account.modules (module_id) ON DELETE CASCADE
);

COMMENT ON TABLE account.permissions IS 'Permissões granulares vinculadas a módulos, atribuídas a roles para controle de acesso (RBAC).';
COMMENT ON COLUMN account.permissions.permission_id   IS 'Identificador único da permissão (UUID).';
COMMENT ON COLUMN account.permissions.module_id       IS 'Módulo ao qual esta permissão pertence (FK para account.modules).';
COMMENT ON COLUMN account.permissions.permission_name IS 'Nome legível da permissão (ex: "Editar Cadastro de Parceiros").';
COMMENT ON COLUMN account.permissions.permission_key  IS 'Chave técnica única usada no código para checagem (ex: "establishments:update").';
COMMENT ON COLUMN account.permissions.description     IS 'Descrição opcional do que esta permissão concede ao usuário.';
COMMENT ON COLUMN account.permissions.created_at      IS 'Timestamp de criação do registro.';
COMMENT ON COLUMN account.permissions.updated_at      IS 'Timestamp da última atualização do registro.';

-- Tabela: Roles (RBAC) - ATUALIZADA (S/ Slug, C/ Account_Type e Is_Owner)
CREATE TABLE IF NOT EXISTS account.roles (
    role_id uuid DEFAULT gen_random_uuid() NOT NULL,
    role_name character varying(50) NOT NULL,
    account_type character varying(30) NOT NULL,
    is_owner boolean NOT NULL DEFAULT false,
    is_system boolean DEFAULT false NOT NULL,
    modules jsonb DEFAULT '["default"]'::jsonb,
    permissions jsonb DEFAULT '["default"]'::jsonb,
    created_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    updated_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    CONSTRAINT roles_pkey PRIMARY KEY (role_id),
    CONSTRAINT roles_account_type_is_owner_unique UNIQUE (account_type, is_owner)
);
COMMENT ON TABLE account.roles IS 'Gerenciamento de perfis de acesso segmentados por tipo de conta e hierarquia de dono.';
COMMENT ON COLUMN account.roles.role_id      IS 'Identificador único da role (UUID).';
COMMENT ON COLUMN account.roles.role_name    IS 'Nome legível da role exibido na interface (ex: "Dono Escritório", "Contador Autônomo").';
COMMENT ON COLUMN account.roles.account_type IS 'Tipo de conta ao qual a role pertence: OFFICE, ACCOUNTANT, COMPANY, INDIVIDUAL.';
COMMENT ON COLUMN account.roles.is_owner     IS 'Indica se é a role principal (dona) do tenant. Apenas uma role owner por account_type.';
COMMENT ON COLUMN account.roles.is_system    IS 'Indica se a role foi criada pelo sistema e não pode ser removida pelo usuário.';
COMMENT ON COLUMN account.roles.modules      IS 'Lista JSON dos module_key acessíveis por esta role (ex: ["users", "establishments"]).';
COMMENT ON COLUMN account.roles.permissions  IS 'Lista JSON dos permission_key concedidos por esta role (ex: ["establishments:update", "establishments:sync"]).';
COMMENT ON COLUMN account.roles.created_at   IS 'Timestamp de criação do registro.';
COMMENT ON COLUMN account.roles.updated_at   IS 'Timestamp da última atualização do registro.';

