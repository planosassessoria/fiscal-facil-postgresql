-- Triggers para FTS e Updated_at
CREATE TRIGGER tr_user_fts BEFORE INSERT OR UPDATE OF full_name, display_name, email, cpf
ON account.users FOR EACH ROW EXECUTE FUNCTION account.fn_update_user_fts();

CREATE TRIGGER tr_upd_users BEFORE UPDATE ON account.users
FOR EACH ROW EXECUTE FUNCTION public.fn_update_timestamp();

CREATE TRIGGER tr_upd_roles BEFORE UPDATE ON account.roles
FOR EACH ROW EXECUTE FUNCTION public.fn_update_timestamp();

CREATE TRIGGER tr_upd_modules BEFORE UPDATE ON account.modules
FOR EACH ROW EXECUTE FUNCTION public.fn_update_timestamp();

CREATE TRIGGER tr_upd_permissions BEFORE UPDATE ON account.permissions
FOR EACH ROW EXECUTE FUNCTION public.fn_update_timestamp();

