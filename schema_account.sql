    updated_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
    CONSTRAINT users_sessions_pkey PRIMARY KEY (session_id),
    CONSTRAINT users_sessions_email_fkey FOREIGN KEY (email) REFERENCES account.users(email) ON DELETE CASCADE
