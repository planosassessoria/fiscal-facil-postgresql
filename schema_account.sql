-- Função para atualizar o vetor de busca (Full Text Search)
CREATE OR REPLACE FUNCTION account.fn_update_user_fts()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.user_fts :=
        setweight(to_tsvector('public.simple_portuguese', COALESCE(NEW.full_name, '')), 'A') ||
        setweight(to_tsvector('public.simple_portuguese', COALESCE(NEW.display_name, '')), 'B') ||
        setweight(to_tsvector('public.simple_portuguese', COALESCE(NEW.email, '')), 'C') ||
        setweight(to_tsvector('public.simple_portuguese', COALESCE(NEW.cpf, '')), 'A');
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION account.fn_update_user_fts() IS
    'Atualiza o vetor FTS de account.users. Pesos: full_name e cpf = A, display_name = B, email = C.';

